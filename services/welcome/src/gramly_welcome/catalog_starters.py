def starter_entries() -> list[dict[str, Any]]:
    entries = []
    for slug, title, description, welcome, farewell in STARTER_COPY:
        for kind, texts in (("welcome", welcome), ("farewell", farewell)):
            entries.append({
                "slug": f"{kind}-{slug}", "revision": 1, "kind": kind,
                "title": f"{title} · {'приветствие' if kind == 'welcome' else 'прощание'}",
                "author": "Gramly", "description": description, "tags": [title, "Текст"],
                "conversion": None, "requires_business": False,
                "screenshots": [f"/app/catalog/{kind}-{slug}-r1.png"],
                "spec": {"first_delay_seconds": 0, "steps": [
                    {"payload": {"type": "text", "text": text}, "delay_after_seconds": 30 if i < len(texts) - 1 else 0}
                    for i, text in enumerate(texts)
                ]},
            })
    return entries
